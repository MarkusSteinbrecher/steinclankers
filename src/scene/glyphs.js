// The 11 x 11 mark from build_svgs.py: robot head in light greens, ampersand in level 4.
const AMP = ['01000', '10100', '01000', '10101', '10010', '01101'];
const HEAD_LV = [2, 2, 1, 2, 2, 2, 1, 2, 2, 1, 2];
export function markGrid() {
  const g = Array.from({ length: 11 }, () => new Array(11).fill(0));
  for (let r = 0; r < 11; r++) {
    for (let c = 0; c < 11; c++) {
      const head = (c >= 2 && c <= 8 && r >= 2 && r <= 9) || (c === 5 && r === 1) || ((c === 1 || c === 9) && (r === 5 || r === 6));
      if (head) g[r][c] = HEAD_LV[(r * 5 + c * 3) % 11];
      if (c >= 3 && c <= 7 && r >= 3 && r <= 8 && AMP[r - 3][c - 3] === '1') g[r][c] = 4;
    }
  }
  return g;
}
